-- ---------- ฟังก์ชันช่วย ----------
create or replace function is_admin() returns boolean
language sql stable security definer set search_path = public as $$
  select exists (select 1 from admin_users where user_id = auth.uid());
$$;

create or replace function get_setting(p_key text) returns text
language sql stable security definer set search_path = public as $$
  select value from settings where key = p_key;
$$;

-- เวลาไทย (UTC+7 ไม่มีเวลาออมแสง) ไม่พึ่งฐานข้อมูลเขตเวลา
create or replace function bkk(ts timestamptz) returns timestamp
language sql immutable as $$ select (ts at time zone 'UTC') + interval '7 hours' $$;

create or replace function bkk_day_start(ts timestamptz) returns timestamptz
language sql immutable as $$ select (date_trunc('day', (ts at time zone 'UTC') + interval '7 hours') - interval '7 hours') at time zone 'UTC' $$;

create or replace function th_date(ts timestamptz) returns text
language sql immutable as $$
  select case when ts is null then null else
    extract(day from bkk(ts))::int || ' ' ||
    (array['ม.ค.','ก.พ.','มี.ค.','เม.ย.','พ.ค.','มิ.ย.','ก.ค.','ส.ค.','ก.ย.','ต.ค.','พ.ย.','ธ.ค.'])[extract(month from bkk(ts))::int] || ' ' ||
    (extract(year from bkk(ts))::int + 543) end
$$;

create or replace function th_dt(ts timestamptz) returns text
language sql immutable as $$ select case when ts is null then null else th_date(ts) || ' ' || to_char(bkk(ts), 'HH24:MI') end $$;

-- "วันที่ 9 พ.ย. 2569" หรือ "วันที่ 9 พ.ย. 2569 ถึง 11 พ.ย. 2569"
create or replace function th_date_span(s timestamptz, e timestamptz) returns text
language sql immutable as $$
  select case when th_date(s) = th_date(e - interval '1 microsecond') then 'วันที่ ' || th_date(s)
    else 'วันที่ ' || th_date(s) || ' ถึง ' || th_date(e - interval '1 microsecond') end
$$;

create or replace function status_label(p_status text) returns text
language sql stable security definer set search_path = public as $$
  select case p_status
    when 'pending' then 'รออนุมัติ'
    when 'approved' then case when get_setting('require_approval') = '1' then 'อนุมัติ' else 'จองแล้ว' end
    when 'rejected' then 'ไม่อนุมัติ'
    when 'cancelled' then 'ยกเลิก'
    when 'completed' then 'เสร็จสิ้น' end
$$;

create or replace function admin_name() returns text
language sql stable security definer set search_path = public as $$
  select coalesce((select display_name from admin_users where user_id = auth.uid()), 'ผู้ดูแลระบบ')
$$;

create or replace function require_admin() returns void
language plpgsql stable security definer set search_path = public as $$
begin
  if not is_admin() then raise exception 'เฉพาะผู้ดูแลระบบเท่านั้นที่ทำรายการนี้ได้' using errcode = 'PT403'; end if;
end $$;

-- ข้อความ → จำนวนเต็ม (ไม่ใช่ตัวเลข = null)
create or replace function to_int(p text) returns int
language sql immutable as $$ select case when trim(coalesce(p, '')) ~ '^-?\d{1,9}$' then trim(p)::int end $$;

create or replace function next_vehicle_seq(p_vehicle bigint) returns int
language sql stable security definer set search_path = public as $$
  select greatest(coalesce((select max(vehicle_seq) from bookings where vehicle_id = p_vehicle), 0),
                  coalesce((select seq_start - 1 from vehicles where id = p_vehicle), 0)) + 1
$$;

-- ---------- การจองแบบละเอียด (ใช้ภายในฟังก์ชัน) ----------
create or replace view booking_full with (security_invoker = true) as
  select b.*, v.plate, v.brand, v.model, v.seats as vehicle_seats, v.driver_name as vehicle_driver, t.name as type_name,
         tl.driver_name as trip_driver, tl.depart_at, tl.depart_mileage, tl.return_at, tl.return_mileage, tl.note as trip_note
  from bookings b
  left join vehicles v on v.id = b.vehicle_id
  left join vehicle_types t on t.id = b.type_id
  left join trip_logs tl on tl.booking_id = b.id;

create or replace function booking_json(p_id bigint) returns jsonb
language sql stable security definer set search_path = public as $$
  select to_jsonb(f) - 'owner_token' - 'approved_by_admin' || jsonb_build_object(
    'status_label', status_label(f.status),
    'decided_by', case when f.approved_by_admin then 1 end,
    'distance', case when f.depart_mileage is not null and f.return_mileage is not null then f.return_mileage - f.depart_mileage end,
    'overdue', f.status = 'approved' and f.end_at < now() and f.return_at is null)
  from booking_full f where f.id = p_id
$$;

-- ผู้เรียกมีสิทธิ์ดูการจองนี้หรือไม่ (ผู้ดูแล หรือถือรหัสลับ)
create or replace function can_see_booking(p_id bigint, p_tokens text[]) returns boolean
language sql stable security definer set search_path = public as $$
  select is_admin() or exists (select 1 from bookings where id = p_id and owner_token is not null and owner_token = any(coalesce(p_tokens, '{}')))
$$;

-- ---------- ตรวจว่ารถว่าง ----------
create or replace function booking_conflicts(p_vehicle bigint, p_start timestamptz, p_end timestamptz, p_exclude bigint default 0)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare
  v vehicles; s timestamptz := p_start; e timestamptz := p_end; day_mode boolean;
  res jsonb := '[]'::jsonb; r record;
begin
  select * into v from vehicles where id = p_vehicle;
  if not found then raise exception 'ไม่พบรถที่เลือก' using errcode = 'PT404'; end if;
  day_mode := coalesce(get_setting('conflict_mode'), 'day') <> 'time';
  if day_mode then
    -- รายวัน: รถมีการจองใด ๆ ในวันเดียวกันถือว่าชน
    s := bkk_day_start(p_start);
    e := bkk_day_start(p_end - interval '1 microsecond') + interval '1 day';
  end if;
  if not v.active then
    res := res || jsonb_build_array(jsonb_build_object('kind', 'inactive', 'message', 'รถ ' || v.plate || ' ถูกปิดใช้งานอยู่'));
  end if;
  for r in select * from maintenance m where m.vehicle_id = p_vehicle and m.start_at < e and (m.end_at is null or m.end_at > s) order by m.start_at loop
    res := res || jsonb_build_array(jsonb_build_object('kind', 'maintenance', 'id', r.id, 'start_at', r.start_at, 'end_at', r.end_at,
      'message', 'รถอยู่ระหว่างซ่อมบำรุง ' || th_dt(r.start_at) || ' ถึง ' || coalesce(th_dt(r.end_at), 'ยังไม่กำหนดวันเสร็จ')
        || case when r.description <> '' then ' (' || r.description || ')' else '' end));
  end loop;
  for r in select * from bookings b where b.vehicle_id = p_vehicle and b.id <> coalesce(p_exclude, 0)
             and b.status in ('pending', 'approved') and b.start_at < e and b.end_at > s order by b.start_at loop
    res := res || jsonb_build_array(jsonb_build_object('kind', 'booking', 'id', r.id, 'code', r.code, 'status', r.status, 'start_at', r.start_at, 'end_at', r.end_at,
      'message', case when day_mode then 'รถคันนี้มีการจองแล้ว ' || th_date_span(r.start_at, r.end_at)
                      else 'มีการจอง ช่วง ' || th_dt(r.start_at) || ' ถึง ' || th_dt(r.end_at) end
        || ' (' || r.code || ' · ' || status_label(r.status) || case when r.requester_department <> '' then ' · ' || r.requester_department else '' end || ')'));
  end loop;
  -- รถที่ออกไปแล้วแต่ยังไม่บันทึกขากลับ: ไม่ว่างจนถึงเวลากลับตามการจอง หรือจนถึงตอนนี้ถ้าเลยกำหนด
  for r in select b.code, b.end_at, t.depart_at from trip_logs t join bookings b on b.id = t.booking_id
             where t.vehicle_id = p_vehicle and t.depart_at is not null and t.return_at is null
               and b.id <> coalesce(p_exclude, 0) and b.status = 'approved' loop
    if s < greatest(r.end_at, now()) and e > r.depart_at
       and not exists (select 1 from jsonb_array_elements(res) x where x->>'code' = r.code) then
      res := res || jsonb_build_array(jsonb_build_object('kind', 'trip', 'code', r.code,
        'message', 'รถออกเดินทางตามการจอง ' || r.code || ' ตั้งแต่ ' || th_dt(r.depart_at) || ' และยังไม่บันทึกขากลับ'));
    end if;
  end loop;
  return res;
end $$;

create or replace function check_availability(p_vehicle bigint, p_start timestamptz, p_end timestamptz, p_exclude bigint default 0)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare c jsonb;
begin
  if p_start is null or p_end is null then raise exception 'กรุณาระบุวันและเวลาออกเดินทางและเวลากลับให้ถูกต้อง' using errcode = 'PT400'; end if;
  if p_end <= p_start then raise exception 'วันเวลากลับต้องอยู่หลังวันเวลาออกเดินทาง' using errcode = 'PT400'; end if;
  c := booking_conflicts(p_vehicle, p_start, p_end, p_exclude);
  return jsonb_build_object('available', jsonb_array_length(c) = 0, 'conflicts', c);
end $$;

-- ตรวจที่นั่งและความว่าง — ไม่ผ่านจะโยน error พร้อมรายละเอียด (PT409 → HTTP 409)
create or replace function assert_vehicle_fits(p_vehicle bigint, p_start timestamptz, p_end timestamptz, p_pax int, p_exclude bigint)
returns vehicles language plpgsql volatile security definer set search_path = public as $$
declare v vehicles; c jsonb;
begin
  -- ล็อกรถคันนี้ระหว่างตรวจ+บันทึก กันการจองพร้อมกันสองรายการ
  perform pg_advisory_xact_lock(4242, p_vehicle::int);
  select * into v from vehicles where id = p_vehicle;
  if not found then raise exception 'ไม่พบรถที่เลือก' using errcode = 'PT400'; end if;
  if p_pax > v.seats then
    raise exception 'จำนวนผู้เดินทาง % คน เกินจำนวนที่นั่งของรถ % (% ที่นั่ง)', p_pax, v.plate, v.seats using errcode = 'PT400';
  end if;
  c := booking_conflicts(p_vehicle, p_start, p_end, p_exclude);
  if jsonb_array_length(c) > 0 then
    raise exception using message = 'รถ ' || v.plate || ' ไม่ว่างในช่วงเวลาที่เลือก', detail = c::text, errcode = 'PT409';
  end if;
  return v;
end $$;

create or replace function log_event(p_booking bigint, p_name text, p_action text, p_note text default '')
returns void language sql volatile security definer set search_path = public as $$
  insert into booking_events(booking_id, user_name, action, note) values (p_booking, coalesce(p_name, ''), p_action, coalesce(p_note, ''));
$$;

-- ---------- สร้างการจอง (ผู้ไม่ได้ล็อกอินเรียกได้) ----------
create or replace function create_booking(p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  adm boolean := is_admin();
  req_approval boolean := coalesce(get_setting('require_approval'), '0') = '1';
  v_name text := left(trim(coalesce(p->>'requester_name', '')), 120);
  v_dept text := left(trim(coalesce(p->>'requester_department', '')), 160);
  v_purpose text := left(trim(coalesce(p->>'purpose', '')), 1000);
  v_dest text := left(trim(coalesce(p->>'destination', '')), 500);
  v_pax int := to_int(p->>'passenger_count');
  v_type bigint := to_int(p->>'type_id');
  v_type_other text := left(trim(coalesce(p->>'type_other', '')), 100);
  v_vehicle bigint := to_int(p->>'vehicle_id');
  v_need_driver boolean := coalesce(p->>'need_driver', 'true') not in ('false', '0');
  s timestamptz; e timestamptz; v vehicles; new_id bigint; tok text; v_code text; prefix text; n int;
begin
  if v_name = '' then raise exception 'กรุณาระบุชื่อผู้ขอใช้รถ' using errcode = 'PT400'; end if;
  if v_dept = '' then raise exception 'กรุณาระบุฝ่าย/สังกัด' using errcode = 'PT400'; end if;
  if v_purpose = '' then raise exception 'กรุณาระบุวัตถุประสงค์/เหตุผลในการใช้รถ' using errcode = 'PT400'; end if;
  if v_dest = '' then raise exception 'กรุณาระบุสถานที่ไป/จุดหมาย' using errcode = 'PT400'; end if;
  if v_pax is null or v_pax < 1 or v_pax > 100 then raise exception 'จำนวนผู้เดินทางต้องเป็นตัวเลข 1–100 คน' using errcode = 'PT400'; end if;
  if v_type is null and v_type_other = '' then raise exception 'กรุณาเลือกประเภทรถ' using errcode = 'PT400'; end if;
  if v_type is not null and not exists (select 1 from vehicle_types where id = v_type) then raise exception 'ไม่พบประเภทรถที่เลือก' using errcode = 'PT400'; end if;
  begin
    s := (p->>'start_at')::timestamptz; e := (p->>'end_at')::timestamptz;
  exception when others then s := null;
  end;
  if s is null or e is null then raise exception 'กรุณาระบุวันและเวลาออกเดินทางและเวลากลับให้ถูกต้อง' using errcode = 'PT400'; end if;
  if e <= s then raise exception 'วันเวลากลับต้องอยู่หลังวันเวลาออกเดินทาง' using errcode = 'PT400'; end if;
  if not adm and s < now() - interval '10 minutes' then raise exception 'ไม่สามารถจองย้อนหลังได้ กรุณาเลือกเวลาออกเดินทางในอนาคต' using errcode = 'PT400'; end if;
  if not req_approval and v_vehicle is null then raise exception 'กรุณาเลือกรถที่ต้องการจอง' using errcode = 'PT400'; end if;

  if v_vehicle is not null then
    v := assert_vehicle_fits(v_vehicle, s, e, v_pax, 0);
    if v_type is null then v_type := v.type_id; end if;
  end if;

  perform pg_advisory_xact_lock(4243, 0); -- ออกเลขที่การจองทีละรายการ
  prefix := 'RQ-' || (extract(year from bkk(now()))::int + 543) || '-';
  select coalesce(max(substr(code, length(prefix) + 1)::int), 0) + 1 into n
    from bookings where code like prefix || '%' and substr(code, length(prefix) + 1) ~ '^\d+$';
  v_code := prefix || lpad(n::text, 4, '0');
  tok := replace(gen_random_uuid()::text, '-', '');

  insert into bookings(code, requester_name, requester_position, requester_department, requester_phone, purpose, destination,
      companions, passenger_count, type_id, type_other, vehicle_id, vehicle_seq, need_driver, assigned_driver, start_at, end_at, note,
      status, decided_at, owner_token)
    values (v_code, v_name, left(trim(coalesce(p->>'requester_position', '')), 120), v_dept, left(trim(coalesce(p->>'requester_phone', '')), 40),
      v_purpose, v_dest, left(trim(coalesce(p->>'companions', '')), 2000), v_pax, v_type, v_type_other, v_vehicle,
      case when v_vehicle is not null then next_vehicle_seq(v_vehicle) end, v_need_driver,
      case when not req_approval and v_need_driver then coalesce(v.driver_name, '') else '' end, s, e, left(trim(coalesce(p->>'note', '')), 2000),
      case when req_approval then 'pending' else 'approved' end, case when req_approval then null else now() end, tok)
    returning id into new_id;

  perform log_event(new_id, case when adm then admin_name() else v_name end, 'create', case when v_vehicle is null then 'ยังไม่ระบุรถ ให้ผู้ดูแลจัดรถ' else '' end);
  if not req_approval then
    perform log_event(new_id, case when adm then admin_name() else v_name end, 'confirm', 'จองรถ ' || v.plate || ' สำเร็จ (ไม่ต้องรออนุมัติ)');
  end if;
  return booking_json(new_id) || jsonb_build_object('owner_token', tok,
    'events', (select jsonb_agg(to_jsonb(x) order by x.at, x.id) from booking_events x where x.booking_id = new_id));
end $$;

