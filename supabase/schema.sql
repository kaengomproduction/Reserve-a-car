-- ---------- ตาราง ----------
create table if not exists vehicle_types (
  id          bigint generated by default as identity primary key,
  name        text not null unique,
  sort_order  int not null default 0,
  active      boolean not null default true
);

create table if not exists vehicles (
  id           bigint generated by default as identity primary key,
  plate        text not null unique,
  brand        text not null default '',
  model        text not null default '',
  type_id      bigint not null references vehicle_types(id),
  seats        int not null default 4 check (seats between 1 and 100),
  color        text not null default '',
  driver_name  text not null default '',
  driver_phone text not null default '',
  mileage      int check (mileage >= 0),
  seq_start    int not null default 1 check (seq_start >= 1),
  note         text not null default '',
  active       boolean not null default true,
  is_demo      boolean not null default false,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

create table if not exists maintenance (
  id          bigint generated by default as identity primary key,
  vehicle_id  bigint not null references vehicles(id) on delete cascade,
  start_at    timestamptz not null,
  end_at      timestamptz,
  description text not null default '',
  created_by  text not null default '',
  created_at  timestamptz not null default now(),
  is_demo     boolean not null default false,
  check (end_at is null or end_at > start_at)
);

create table if not exists bookings (
  id                   bigint generated by default as identity primary key,
  code                 text not null unique,
  requester_name       text not null,
  requester_position   text not null default '',
  requester_department text not null default '',
  requester_phone      text not null default '',
  purpose              text not null,
  destination          text not null,
  companions           text not null default '',
  passenger_count      int not null default 1 check (passenger_count between 1 and 100),
  type_id              bigint references vehicle_types(id),
  type_other           text not null default '',
  vehicle_id           bigint references vehicles(id) on delete set null,
  vehicle_seq          int,
  need_driver          boolean not null default true,
  assigned_driver      text not null default '',
  start_at             timestamptz not null,
  end_at               timestamptz not null,
  note                 text not null default '',
  status               text not null default 'pending' check (status in ('pending','approved','rejected','cancelled','completed')),
  decision_note        text not null default '',
  approved_by_admin    boolean not null default false,
  decided_by_name      text not null default '',
  decided_at           timestamptz,
  cancel_reason        text not null default '',
  owner_token          text,
  created_at           timestamptz not null default now(),
  updated_at           timestamptz not null default now(),
  is_demo              boolean not null default false,
  check (end_at > start_at)
);
create index if not exists idx_bookings_vehicle_time on bookings(vehicle_id, start_at, end_at);
create index if not exists idx_bookings_owner_token on bookings(owner_token);

create table if not exists trip_logs (
  booking_id     bigint primary key references bookings(id) on delete cascade,
  vehicle_id     bigint references vehicles(id) on delete set null,
  driver_name    text not null default '',
  depart_at      timestamptz,
  depart_mileage int,
  return_at      timestamptz,
  return_mileage int,
  note           text not null default '',
  recorded_by    text not null default '',
  updated_at     timestamptz not null default now()
);

create table if not exists booking_events (
  id          bigint generated by default as identity primary key,
  booking_id  bigint not null references bookings(id) on delete cascade,
  at          timestamptz not null default now(),
  user_name   text not null default '',
  action      text not null,
  note        text not null default ''
);
create index if not exists idx_events_booking on booking_events(booking_id);

create table if not exists people (
  id             bigint generated by default as identity primary key,
  name           text not null unique,
  position       text not null default '',
  department     text not null default '',
  phone          text not null default '',
  is_staff       boolean not null default true,
  is_driver      boolean not null default false,
  is_responsible boolean not null default false,
  is_approver    boolean not null default false,
  active         boolean not null default true,
  sort_order     int not null default 0,
  is_demo        boolean not null default false
);

create table if not exists presets (
  id         bigint generated by default as identity primary key,
  kind       text not null check (kind in ('destination','purpose')),
  text       text not null,
  sort_order int not null default 0,
  is_demo    boolean not null default false,
  unique (kind, text)
);

create table if not exists settings (
  key   text primary key,
  value text not null default ''
);

-- ผู้ดูแลระบบ: user_id จาก Supabase Auth (Authentication → Users)
