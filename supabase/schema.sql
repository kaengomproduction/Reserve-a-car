-- รายการการจอง: ผู้ดูแลเห็นทั้งหมด / ผู้ไม่ได้ล็อกอินเห็นเฉพาะที่ถือรหัสลับ
create or replace function get_bookings(p_tokens text[] default '{}', p_status text default null, p_q text default null,
                                        p_trip boolean default false, p_order text default null)
returns jsonb language sql stable security definer set search_path = public as $$
  select coalesce(jsonb_agg(booking_json(x.id) order by
           case when p_order = 'start' then x.start_at end asc,
           case when coalesce(p_order, '') <> 'start' then x.created_at end desc, x.id desc), '[]'::jsonb)
  from (
    select b.id, b.start_at, b.created_at from bookings b left join vehicles v on v.id = b.vehicle_id
    where (is_admin() or (b.owner_token is not null and b.owner_token = any(coalesce(p_tokens, '{}'))))
      and (coalesce(p_status, '') = '' or b.status = p_status)
      and (not coalesce(p_trip, false) or (b.status in ('approved', 'completed') and b.vehicle_id is not null))
      and (coalesce(p_q, '') = '' or b.code ilike '%' || p_q || '%' or b.requester_name ilike '%' || p_q || '%'
           or b.destination ilike '%' || p_q || '%' or b.purpose ilike '%' || p_q || '%' or v.plate ilike '%' || p_q || '%')
    order by b.created_at desc limit 500
  ) x
$$;

-- ปฏิทิน: การจองของผู้อื่นแสดงเฉพาะช่วงเวลาและหน่วยงาน
create or replace function get_schedule(p_from timestamptz, p_to timestamptz, p_tokens text[] default '{}')
returns jsonb language sql stable security definer set search_path = public as $$
  select jsonb_build_object(
    'from', p_from, 'to', p_to,
    'vehicles', coalesce((select jsonb_agg(jsonb_build_object('id', v.id, 'plate', v.plate, 'brand', v.brand, 'model', v.model, 'seats', v.seats,
                  'active', v.active, 'type_id', v.type_id, 'type_name', t.name) order by t.sort_order, v.plate)
                from vehicles v join vehicle_types t on t.id = v.type_id), '[]'::jsonb),
    'bookings', coalesce((select jsonb_agg(
                  case when can_see_booking(b.id, p_tokens) then booking_json(b.id) || jsonb_build_object('can_view', true)
                  else jsonb_build_object('id', null, 'code', b.code, 'status', b.status, 'status_label', status_label(b.status),
                       'vehicle_id', b.vehicle_id, 'plate', v.plate, 'type_name', t.name, 'start_at', b.start_at, 'end_at', b.end_at,
                       'requester_department', b.requester_department, 'can_view', false) end order by b.start_at)
                from bookings b left join vehicles v on v.id = b.vehicle_id left join vehicle_types t on t.id = b.type_id
                where b.status in ('pending', 'approved', 'completed') and b.start_at < p_to and b.end_at > p_from), '[]'::jsonb),
    'maintenance', coalesce((select jsonb_agg(to_jsonb(m) || jsonb_build_object('plate', v.plate) order by m.start_at)
                from maintenance m join vehicles v on v.id = m.vehicle_id
                where m.start_at < p_to and (m.end_at is null or m.end_at > p_from)), '[]'::jsonb))
$$;

-- สถานะรถทุกคันในช่วง [p_from, p_to] (ไม่ระบุ = ขณะนี้)
create or replace function vehicle_states(p_from timestamptz default null, p_to timestamptz default null)
returns jsonb language plpgsql stable security definer set search_path = public as $$
declare f timestamptz := coalesce(p_from, now()); t timestamptz; inc_now boolean;
begin
  t := coalesce(p_to, f + interval '1 minute');
  if t < f then raise exception 'ช่วงเวลาสิ้นสุดต้องอยู่หลังเวลาเริ่มต้น' using errcode = 'PT400'; end if;
  inc_now := f <= now() + interval '1 minute' and t >= now();
  return coalesce((
    select jsonb_agg(to_jsonb(v) || jsonb_build_object(
        'type_name', ty.name,
        'state', st.state,
        'state_label', case st.state when 'available' then 'ว่าง' when 'booked' then 'ถูกจอง' when 'in_use' then 'กำลังใช้งาน' else 'ไม่พร้อมใช้งาน' end,
        'state_reason', st.reason, 'state_detail', st.detail,
        'maintenance', coalesce(m.list, '[]'::jsonb), 'bookings_in_range', bk.n, 'next_booking', nb.j)
      order by v.active desc, ty.sort_order, v.plate)
    from vehicles v
    join vehicle_types ty on ty.id = v.type_id
    left join lateral (select jsonb_agg(to_jsonb(mm) order by mm.start_at) as list, (array_agg(mm.end_at order by mm.start_at))[1] as first_end
                       from maintenance mm where mm.vehicle_id = v.id and mm.start_at < t and (mm.end_at is null or mm.end_at > f)) m on true
    left join lateral (select count(*)::int as n, coalesce(bool_and(b.status = 'pending'), false) as all_pending,
                              (array_agg(b.code) filter (where b.status = 'approved' and b.start_at <= now() and b.end_at > now()))[1] as cur_code
                       from bookings b where b.vehicle_id = v.id and b.status in ('pending', 'approved') and b.start_at < t and b.end_at > f) bk on true
    left join lateral (select b.code from trip_logs tl join bookings b on b.id = tl.booking_id
                       where tl.vehicle_id = v.id and tl.depart_at is not null and tl.return_at is null and b.status = 'approved' limit 1) tr on true
    left join lateral (select jsonb_build_object('id', b.id, 'code', b.code, 'status', b.status, 'start_at', b.start_at, 'end_at', b.end_at) as j
                       from bookings b where b.vehicle_id = v.id and b.status in ('pending', 'approved') and b.end_at > now() order by b.start_at limit 1) nb on true
    cross join lateral (select
        case when not v.active or m.list is not null then 'unavailable'
             when inc_now and (tr.code is not null or bk.cur_code is not null) then 'in_use'
             when bk.n > 0 then 'booked' else 'available' end as state,
        case when not v.active then 'inactive' when m.list is not null then 'maintenance'
             when inc_now and (tr.code is not null or bk.cur_code is not null) then 'trip'
             when bk.n > 0 then case when bk.all_pending then 'pending' else 'approved' end else '' end as reason,
        case when not v.active then 'ปิดใช้งาน'
             when m.list is not null then 'ซ่อมบำรุงถึง ' || coalesce(th_dt(m.first_end), 'ยังไม่กำหนด')
             when inc_now and (tr.code is not null or bk.cur_code is not null) then 'ใช้งานตามการจอง ' || coalesce(tr.code, bk.cur_code)
             when bk.n > 0 then bk.n || ' รายการ' || case when bk.all_pending then ' (รออนุมัติ)' else '' end else '' end as detail) st
  ), '[]'::jsonb);
end $$;

