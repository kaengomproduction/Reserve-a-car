create or replace function assign_vehicle(p_id bigint, p_vehicle bigint, p_driver text default null) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare b bookings; v vehicles; drv text;
begin
  perform require_admin();
  select * into b from bookings where id = p_id for update;
  if not found then raise exception 'ไม่พบการจอง' using errcode = 'PT404'; end if;
  if b.status not in ('pending', 'approved') then raise exception 'การจองสถานะ "%" ไม่สามารถเปลี่ยนรถได้', status_label(b.status) using errcode = 'PT400'; end if;
  if p_vehicle is null then raise exception 'กรุณาเลือกรถ' using errcode = 'PT400'; end if;
  v := assert_vehicle_fits(p_vehicle, b.start_at, b.end_at, b.passenger_count, b.id);
  drv := coalesce(left(trim(p_driver), 120), case when b.vehicle_id = p_vehicle then b.assigned_driver else v.driver_name end);
  update bookings set vehicle_id = p_vehicle, assigned_driver = drv, updated_at = now(),
    vehicle_seq = case when b.vehicle_id is distinct from p_vehicle or b.vehicle_seq is null then next_vehicle_seq(p_vehicle) else b.vehicle_seq end
    where id = p_id;
  perform log_event(p_id, admin_name(), 'assign', 'กำหนดรถ ' || v.plate || case when drv <> '' then ' พนักงานขับรถ ' || drv else '' end);
  return get_booking(p_id);
end $$;

create or replace function approve_booking(p_id bigint, p_vehicle bigint default null, p_driver text default null, p_note text default '') returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare b bookings; v vehicles; vid bigint; drv text; v_note text := left(trim(coalesce(p_note, '')), 1000);
begin
  perform require_admin();
  select * into b from bookings where id = p_id for update;
  if not found then raise exception 'ไม่พบการจอง' using errcode = 'PT404'; end if;
  if b.status <> 'pending' then raise exception 'อนุมัติได้เฉพาะการจองที่รออนุมัติ (สถานะปัจจุบัน: %)', status_label(b.status) using errcode = 'PT400'; end if;
  vid := coalesce(p_vehicle, b.vehicle_id);
  if vid is null then raise exception 'กรุณาเลือกรถก่อนอนุมัติ' using errcode = 'PT400'; end if;
  v := assert_vehicle_fits(vid, b.start_at, b.end_at, b.passenger_count, b.id);
  drv := coalesce(left(trim(p_driver), 120), nullif(b.assigned_driver, ''), v.driver_name);
  update bookings set status = 'approved', vehicle_id = vid, assigned_driver = drv, decision_note = v_note, approved_by_admin = true,
    decided_by_name = admin_name(), decided_at = now(), updated_at = now(),
    vehicle_seq = case when b.vehicle_id is distinct from vid or b.vehicle_seq is null then next_vehicle_seq(vid) else b.vehicle_seq end
    where id = p_id;
  perform log_event(p_id, admin_name(), 'approve', concat_ws(' · ', 'รถ ' || v.plate, case when drv <> '' then 'พนักงานขับรถ ' || drv end, nullif(v_note, '')));
  return get_booking(p_id);
end $$;

