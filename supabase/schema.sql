-- บันทึกการใช้รถ: บันทึกขากลับครบแล้วการจองเป็น "เสร็จสิ้น" และอัปเดตเลขไมล์รถ
create or replace function save_trip(p_id bigint, p jsonb) returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare
  b bookings; v_old trip_logs; dep timestamptz; ret timestamptz; dm int; rm int; drv text; v_note text; done boolean;
begin
  perform require_admin();
  select * into b from bookings where id = p_id for update;
  if not found then raise exception 'ไม่พบการจอง' using errcode = 'PT404'; end if;
  if b.status not in ('approved', 'completed') then raise exception 'บันทึกการใช้รถได้เฉพาะการจองที่อนุมัติแล้ว' using errcode = 'PT400'; end if;
  if b.vehicle_id is null then raise exception 'การจองนี้ยังไม่ได้กำหนดรถ' using errcode = 'PT400'; end if;
  select * into v_old from trip_logs where booking_id = p_id;
  begin
    dep := case when p ? 'depart_at' then nullif(p->>'depart_at', '')::timestamptz else v_old.depart_at end;
    ret := case when p ? 'return_at' then nullif(p->>'return_at', '')::timestamptz else v_old.return_at end;
  exception when others then raise exception 'วันเวลาที่บันทึกไม่ถูกต้อง' using errcode = 'PT400';
  end;
  dm := case when p ? 'depart_mileage' then to_int(p->>'depart_mileage') else v_old.depart_mileage end;
  rm := case when p ? 'return_mileage' then to_int(p->>'return_mileage') else v_old.return_mileage end;
  if (p ? 'depart_mileage' and coalesce(p->>'depart_mileage', '') <> '' and dm is null)
     or (p ? 'return_mileage' and coalesce(p->>'return_mileage', '') <> '' and rm is null) or dm < 0 or rm < 0 then
    raise exception 'เลขไมล์ต้องเป็นจำนวนเต็มไม่ติดลบ' using errcode = 'PT400';
  end if;
  drv := left(trim(coalesce(case when p ? 'driver_name' then p->>'driver_name' end, v_old.driver_name, b.assigned_driver, '')), 120);
  v_note := left(trim(coalesce(case when p ? 'note' then p->>'note' end, v_old.note, '')), 1000);
  if (ret is not null or rm is not null) and (dep is null or dm is null) then raise exception 'กรุณาบันทึกเวลาและเลขไมล์ขาออกก่อนบันทึกขากลับ' using errcode = 'PT400'; end if;
  if dep is not null and ret is not null and ret <= dep then raise exception 'เวลากลับต้องอยู่หลังเวลาออกเดินทาง' using errcode = 'PT400'; end if;
  if dm is not null and rm is not null and rm < dm then raise exception 'เลขไมล์ขากลับต้องไม่น้อยกว่าเลขไมล์ขาออก' using errcode = 'PT400'; end if;
  if dep is not null and dm is null then raise exception 'กรุณาระบุเลขไมล์ขาออก' using errcode = 'PT400'; end if;
  if ret is not null and rm is null then raise exception 'กรุณาระบุเลขไมล์ขากลับ' using errcode = 'PT400'; end if;
  if rm is not null and ret is null then raise exception 'กรุณาระบุวันเวลากลับถึง' using errcode = 'PT400'; end if;
  if dep is not null and dep > now() + interval '5 minutes' then raise exception 'เวลาออกเดินทางต้องไม่เป็นเวลาในอนาคต' using errcode = 'PT400'; end if;

  insert into trip_logs(booking_id, vehicle_id, driver_name, depart_at, depart_mileage, return_at, return_mileage, note, recorded_by, updated_at)
    values (p_id, b.vehicle_id, drv, dep, dm, ret, rm, v_note, admin_name(), now())
    on conflict (booking_id) do update set vehicle_id = excluded.vehicle_id, driver_name = excluded.driver_name, depart_at = excluded.depart_at,
      depart_mileage = excluded.depart_mileage, return_at = excluded.return_at, return_mileage = excluded.return_mileage, note = excluded.note,
      recorded_by = excluded.recorded_by, updated_at = excluded.updated_at;
  done := ret is not null and rm is not null;
  if done then
    update vehicles set mileage = greatest(coalesce(mileage, 0), rm), updated_at = now() where id = b.vehicle_id;
    if b.status = 'approved' then update bookings set status = 'completed', updated_at = now() where id = p_id; end if;
  elsif dm is not null then
    update vehicles set mileage = greatest(coalesce(mileage, 0), dm), updated_at = now() where id = b.vehicle_id;
  end if;
  perform log_event(p_id, admin_name(), 'trip', case when done then 'บันทึกขากลับ ระยะทางรวม ' || to_char(rm - dm, 'FM999,999,999') || ' กม.'
                                                     when dep is not null then 'บันทึกขาออก' else 'แก้ไขบันทึกการใช้รถ' end);
  return get_booking(p_id);
end $$;

