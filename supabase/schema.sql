-- รายชื่อสำหรับผู้ไม่ได้ล็อกอิน (ไม่มีเบอร์โทร) — view แบบ definer จึงอ่านได้แม้ตาราง people จำกัดสิทธิ์
create or replace view people_public as
  select id, name, position, department, '' as phone, is_staff, is_driver, is_responsible, is_approver, active, sort_order, is_demo
  from people where active;

-- ---------- สิทธิ์ (Row Level Security) ----------
alter table vehicle_types  enable row level security;
alter table vehicles       enable row level security;
alter table maintenance    enable row level security;
alter table bookings       enable row level security;
alter table trip_logs      enable row level security;
alter table booking_events enable row level security;
alter table people         enable row level security;
alter table presets        enable row level security;
alter table settings       enable row level security;
alter table admin_users    enable row level security;

do $$
declare t text;
begin
  -- อ่านได้ทุกคน เขียนได้เฉพาะผู้ดูแล
  foreach t in array array['vehicle_types', 'vehicles', 'maintenance', 'presets', 'settings'] loop
    execute format('drop policy if exists "public read" on %I', t);
    execute format('create policy "public read" on %I for select using (true)', t);
    execute format('drop policy if exists "admin write" on %I', t);
    execute format('create policy "admin write" on %I for all using (is_admin()) with check (is_admin())', t);
  end loop;
  -- ผู้ดูแลเท่านั้น (ผู้ไม่ได้ล็อกอินใช้ผ่านฟังก์ชันด้านบน)
  foreach t in array array['bookings', 'trip_logs', 'booking_events', 'people'] loop
    execute format('drop policy if exists "admin all" on %I', t);
    execute format('create policy "admin all" on %I for all using (is_admin()) with check (is_admin())', t);
  end loop;
end $$;

drop policy if exists "own row" on admin_users;
create policy "own row" on admin_users for select using (user_id = auth.uid());
drop policy if exists "own name" on admin_users;
create policy "own name" on admin_users for update using (user_id = auth.uid()) with check (user_id = auth.uid());

grant select on vehicle_types, vehicles, maintenance, presets, settings, people_public to anon, authenticated;
grant select, insert, update, delete on vehicle_types, vehicles, maintenance, presets, settings, bookings, trip_logs, booking_events, people to authenticated;
grant select, update on admin_users to authenticated;

