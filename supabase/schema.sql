-- - ผู้ไม่ได้ล็อกอิน (anon) อ่านได้เฉพาะข้อมูลสาธารณะ (รถ ประเภทรถ การซ่อมบำรุง การตั้งค่า รายชื่อแบบไม่มีเบอร์โทร)
--   ส่วนการจองทำผ่านฟังก์ชัน (RPC) ที่ตรวจกฎทั้งหมดในฐานข้อมูล และเห็นการจองของตนผ่านรหัสลับ (owner token)
-- - ผู้ดูแล = ผู้ใช้ Supabase Auth ที่มีชื่ออยู่ในตาราง admin_users (และควรปิดการสมัครสมาชิกใน Supabase)
