-- ---------- ยกเลิก (ผู้จองที่ถือรหัสลับ หรือผู้ดูแล) ----------
create or replace function cancel_booking(p_id bigint, p_reason text, p_tokens text[] default '{}') returns jsonb
language plpgsql volatile security definer set search_path = public as $$
declare b bookings; reason text := left(trim(coalesce(p_reason, '')), 1000);
begin
  if reason = '' then raise exception 'กรุณาระบุเหตุผลการยกเลิก' using errcode = 'PT400'; end if;
  select * into b from bookings where id = p_id for update;
  if not found then raise exception 'ไม่พบการจอง' using errcode = 'PT404'; end if;
  if not can_see_booking(p_id, p_tokens) then
    raise exception 'ยกเลิกได้เฉพาะการจองของตนเอง (ทำจากเครื่องที่ใช้จอง) หรือติดต่อผู้ดูแล' using errcode = 'PT403';
  end if;
  if b.status not in ('pending', 'approved') then raise exception 'การจองสถานะ "%" ยกเลิกไม่ได้', status_label(b.status) using errcode = 'PT400'; end if;
  if exists (select 1 from trip_logs where booking_id = p_id and depart_at is not null) then
    raise exception 'รถออกเดินทางแล้ว ไม่สามารถยกเลิกได้ กรุณาบันทึกขากลับแทน' using errcode = 'PT400';
  end if;
  update bookings set status = 'cancelled', cancel_reason = reason, updated_at = now() where id = p_id;
  perform log_event(p_id, case when is_admin() then admin_name() else b.requester_name end, 'cancel', reason);
  return get_booking(p_id, p_tokens);
end $$;

